export function getContinents(): string[] {
  return Array.from(new Set(WORLD_CITIES.map((c) => c.continent))).sort();
}

export function getCountries(): string[] {
  return Array.from(new Set(WORLD_CITIES.map((c) => c.country))).sort();
}

export function getCitiesByCountry(country: string): City[] {
  return WORLD_CITIES.filter((c) => c.country.toLowerCase() === country.toLowerCase());
}

export function searchCities(query: string): City[] {
  if (!query.trim()) return WORLD_CITIES;
  const q = query.toLowerCase().trim();
  return WORLD_CITIES.filter(
    (c) =>
      c.name.toLowerCase().includes(q) ||
      c.country.toLowerCase().includes(q) ||
      c.countryCode.toLowerCase().includes(q) ||
      c.arterials.some((a) => a.toLowerCase().includes(q))
  );
}
